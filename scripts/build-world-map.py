"""Builds frontend/src/assets/worldMap.ts: the land outlines of Natural Earth's 1:110m land layer (public domain,
https://www.naturalearthdata.com/about/terms-of-use/) as one SVG path in an equirectangular projection, for the offline
map of picture locations. The app draws locations on it without loading anything from the internet.

    python scripts/build-world-map.py            # downloads the pinned GeoJSON and writes the TypeScript module
"""
import json
import sys
import urllib.request
from pathlib import Path

COMMIT = '693f11422f4e08d2da4566b854dda53eb7c39fb3'
URL = f'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/{COMMIT}/geojson/ne_110m_land.geojson'
OUT = Path(__file__).resolve().parents[1] / 'frontend' / 'src' / 'assets' / 'worldMap.ts'
SCALE = 2  # 720 x 360 user units: x = (lon + 180) * 2, y = (90 - lat) * 2


def ring(points) -> str:
    out, last = [], None
    for lon, lat in points:
        p = (round((lon + 180) * SCALE, 1), round((90 - lat) * SCALE, 1))
        if p != last:
            out.append(p)
            last = p
    if len(out) < 3:
        return ''
    return 'M' + 'L'.join(f'{x:g} {y:g}' for x, y in out) + 'Z'


def main():
    with urllib.request.urlopen(URL, timeout=120) as r:
        data = json.load(r)
    parts = []
    for f in data['features']:
        g = f['geometry']
        polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
        for poly in polys:
            for r_ in poly:
                parts.append(ring(r_))
    path = ''.join(p for p in parts if p)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by scripts/build-world-map.py from Natural Earth 1:110m land (public domain), commit ' + COMMIT + '.\n')
        f.write('// Equirectangular: x = (longitude + 180) * 2, y = (90 - latitude) * 2, in a 720 x 360 box.\n')
        f.write(f'export const WORLD_WIDTH = {360 * SCALE};\nexport const WORLD_HEIGHT = {180 * SCALE};\n')
        f.write(f'export const WORLD_LAND = {json.dumps(path)};\n')
    print(f'Wrote {OUT} ({len(path):,} characters, {len(parts)} rings)')


if __name__ == '__main__':
    sys.exit(main())
