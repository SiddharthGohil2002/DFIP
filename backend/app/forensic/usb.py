"""USB device history from a Windows SYSTEM registry hive and setupapi.dev.log.

Sources (all read from copies extracted out of the evidence image):
  SYSTEM\\ControlSetNNN\\Enum\\USBSTOR\\<Disk&Ven_&Prod_&Rev_>\\<instance>
      vendor / product / revision / serial, FriendlyName, and under
      Properties\\{83da6326-97a6-4088-9453-a1923f573b29}:
        0064 first install, 0065 last install, 0066 last arrival, 0067 last removal
      (Windows 7 stores each as <id>\\00000000\\Data; Windows 8+ as the key's default value)
  SYSTEM\\ControlSetNNN\\Enum\\USB\\VID_xxxx&PID_yyyy\\<serial>   -> vendor/product IDs
  SYSTEM\\MountedDevices                                          -> drive letter, volume GUID
  setupapi.dev.log "Device Install ... Section start"            -> first install time (local time,
      converted to UTC with the hive's ActiveTimeBias when available)

No values are inferred: a device or timestamp that is not present in these
sources is reported as absent (None), never estimated.
"""
from __future__ import annotations
import re
from datetime import datetime, timedelta, timezone
from pathlib import Path

from .registry import as_bytes as _as_bytes, control_sets as _control_sets, filetime_to_datetime, signed_dword
from .registry import subkey as _subkey, values as _values

DEVICE_PROPERTIES_GUID = '{83da6326-97a6-4088-9453-a1923f573b29}'
PROPERTY_TIMES = {0x64: 'first_install', 0x65: 'last_install', 0x66: 'last_arrival', 0x67: 'last_removal'}

_DEVICE_CLASS_RE = re.compile(r'^(?P<type>[^&]+)&Ven_(?P<vendor>[^&]*)&Prod_(?P<product>[^&]*)(?:&Rev_(?P<rev>.*))?$', re.I)
_VIDPID_RE = re.compile(r'VID_(?P<vid>[0-9A-F]{4})&PID_(?P<pid>[0-9A-F]{4})', re.I)
_SETUPAPI_DEV_RE = re.compile(r'^>>>\s+\[Device Install[^\]]*? - (?P<dev>[^\]]+)\]')
_SETUPAPI_START_RE = re.compile(r'^>>>\s+Section start (?P<ts>\d{4}/\d{2}/\d{2} \d{2}:\d{2}:\d{2})(?:\.\d+)?')


def _iso(dt):
    return dt.isoformat() if dt else None


def split_instance(instance: str) -> tuple[str, bool]:
    """'AA951D0000007252&0' -> ('AA951D0000007252', True).

    Windows appends '&<n>' to the device's own serial number. When the second
    character is '&' the ID was generated by Windows because the device has no
    unique serial, so it cannot identify a physical device across machines.
    """
    unique = not (len(instance) > 1 and instance[1] == '&')
    serial = re.sub(r'&\d+$', '', instance) if unique else instance
    return serial, unique


def _property_times(instance_key) -> dict:
    """Reads the 0064-0067 device property timestamps in either hive layout."""
    out = {}
    props = _subkey(instance_key, 'Properties')
    guid_key = _subkey(props, DEVICE_PROPERTIES_GUID) if props else None
    if not guid_key:
        return out
    for sub in guid_key.iter_subkeys():
        try:
            prop_id = int(sub.name, 16)
        except ValueError:
            continue
        field = PROPERTY_TIMES.get(prop_id)
        if not field:
            continue
        vals = _values(sub)
        raw = vals.get('(default)', vals.get('', None))
        if raw is None:
            inner = _subkey(sub, '00000000')
            if inner:
                raw = _values(inner).get('Data')
        ts = filetime_to_datetime(raw)
        if ts:
            out[field] = ts
    return out


def _timezone_bias_minutes(reg, control_set: str):
    """UTC = local time + ActiveTimeBias (minutes)."""
    try:
        vals = _values(reg.get_key(f'\\{control_set}\\Control\\TimeZoneInformation'))
    except Exception:
        return None
    return signed_dword(vals.get('ActiveTimeBias', vals.get('Bias')))


def _mounted_devices(reg) -> list[tuple[str, str]]:
    out = []
    try:
        key = reg.get_key('\\MountedDevices')
    except Exception:
        return out
    for v in key.iter_values():
        b = _as_bytes(v.value)
        if not b:
            continue
        try:
            text = b.decode('utf-16-le', errors='ignore')
        except Exception:
            continue
        if 'USBSTOR#' in text.upper():
            out.append((v.name, text))
    return out


def parse_system_hive(path: Path) -> dict:
    result = {'status': 'COMPLETED', 'source_file': str(path), 'devices': [], 'errors': [],
              'current_control_set': None, 'timezone_bias_minutes': None}
    try:
        from regipy.registry import RegistryHive
        reg = RegistryHive(str(path))
    except Exception as exc:
        result.update(status='FAILED', errors=[f'Cannot open registry hive: {exc}'])
        return result

    control_sets = _control_sets(reg)
    result['current_control_set'] = control_sets[0] if control_sets else None
    if control_sets:
        result['timezone_bias_minutes'] = _timezone_bias_minutes(reg, control_sets[0])

    devices: dict[str, dict] = {}
    for cs in control_sets:
        try:
            usbstor = reg.get_key(f'\\{cs}\\Enum\\USBSTOR')
        except Exception:
            continue
        for dev_key in usbstor.iter_subkeys():
            m = _DEVICE_CLASS_RE.match(dev_key.name)
            for inst in dev_key.iter_subkeys():
                serial, unique = split_instance(inst.name)
                d = devices.setdefault(inst.name, {
                    'instance_id': inst.name, 'serial': serial, 'serial_is_unique': unique,
                    'device_class_id': dev_key.name,
                    'device_type': m.group('type') if m else None,
                    'vendor': m.group('vendor') if m else None,
                    'product': m.group('product') if m else None,
                    'revision': m.group('rev') if m else None,
                    'friendly_name': None, 'vid': None, 'pid': None,
                    'drive_letters': [], 'volume_guids': [], 'control_sets': [],
                    'registry_key': f'{cs}\\Enum\\USBSTOR\\{dev_key.name}\\{inst.name}',
                    'source': 'SYSTEM_HIVE', 'source_detail': {},
                })
                d['control_sets'].append(cs)
                vals = _values(inst)
                d['friendly_name'] = d['friendly_name'] or vals.get('FriendlyName')
                for field, ts in _property_times(inst).items():
                    if not d.get(field):
                        d[field] = ts
                        d['source_detail'][field] = f'SYSTEM_HIVE:{cs} Properties {DEVICE_PROPERTIES_GUID}'
        try:
            usb = reg.get_key(f'\\{cs}\\Enum\\USB')
            for vp_key in usb.iter_subkeys():
                vm = _VIDPID_RE.search(vp_key.name)
                if not vm:
                    continue
                for inst in vp_key.iter_subkeys():
                    for d in devices.values():
                        if d['serial_is_unique'] and d['serial'].upper() == inst.name.upper():
                            d['vid'], d['pid'] = vm.group('vid').upper(), vm.group('pid').upper()
        except Exception:
            pass

    for name, text in _mounted_devices(reg):
        for d in devices.values():
            if f'#{d["instance_id"]}#'.upper() in text.upper():
                if name.upper().startswith('\\DOSDEVICES\\'):
                    letter = name.split('\\')[-1]
                    if letter not in d['drive_letters']:
                        d['drive_letters'].append(letter)
                elif 'VOLUME{' in name.upper():
                    guid = name[name.index('{'):]
                    if guid not in d['volume_guids']:
                        d['volume_guids'].append(guid)

    for d in devices.values():
        for field in PROPERTY_TIMES.values():
            d[field] = _iso(d.get(field))
        result['devices'].append(d)
    return result


def parse_setupapi(path: Path, bias_minutes: int | None = None, zone: str | None = None) -> dict:
    """Parses device-install sections of setupapi.dev.log (Vista+) for USB devices.

    Its times are the computer's local time: `zone` (the computer's time zone, daylight saving included) converts
    them to UTC; `bias_minutes` (a fixed UTC = local + bias) is the fallback when only an offset is known.
    """
    from .timezone import local_to_utc
    basis = (f"UTC (converted from the computer's time zone {zone})" if zone else
             'UTC (converted with hive ActiveTimeBias)' if bias_minutes is not None else
             'system local time (no time zone available; stored as-is)')
    result = {'status': 'COMPLETED', 'source_file': str(path), 'entries': [], 'errors': [], 'time_basis': basis}
    try:
        lines = path.read_text(encoding='utf-8', errors='replace').splitlines()
    except OSError as exc:
        result.update(status='FAILED', errors=[str(exc)])
        return result
    pending = None
    for line in lines:
        m = _SETUPAPI_DEV_RE.match(line)
        if m:
            pending = m.group('dev').strip()
            continue
        s = _SETUPAPI_START_RE.match(line)
        if s and pending:
            dev = pending
            pending = None
            upper = dev.upper()
            if not (upper.startswith('USBSTOR\\') or upper.startswith('USB\\')):
                continue
            local = datetime.strptime(s.group('ts'), '%Y/%m/%d %H:%M:%S')
            ts = (local_to_utc(local, zone) if zone else
                  (local + timedelta(minutes=bias_minutes or 0)).replace(tzinfo=timezone.utc))
            parts = dev.split('\\')
            entry = {'device_id': dev, 'bus': parts[0].upper(), 'install_time': ts.isoformat(), 'local_time': s.group('ts')}
            if len(parts) >= 3:
                entry['instance_id'] = parts[2]
                entry['serial'], entry['serial_is_unique'] = split_instance(parts[2])
                cm = _DEVICE_CLASS_RE.match(parts[1])
                if cm:
                    entry.update(device_class_id=parts[1], vendor=cm.group('vendor'), product=cm.group('product'),
                                 revision=cm.group('rev'))
                vm = _VIDPID_RE.search(parts[1])
                if vm:
                    entry.update(vid=vm.group('vid').upper(), pid=vm.group('pid').upper())
            result['entries'].append(entry)
    return result


def merge_usb_sources(hive_devices: list[dict], setupapi_entries: list[dict]) -> list[dict]:
    """Adds setupapi first-install times to registry devices (matched by instance ID),
    and reports USB storage devices seen only in setupapi.dev.log."""
    devices = {d['instance_id'].upper(): d for d in hive_devices}
    by_serial = {d['serial'].upper(): d for d in hive_devices if d.get('serial_is_unique')}
    for e in setupapi_entries:
        inst = (e.get('instance_id') or '').upper()
        if e['bus'] == 'USBSTOR':
            d = devices.get(inst)
            if d is None:
                d = {'instance_id': e.get('instance_id'), 'serial': e.get('serial'),
                     'serial_is_unique': e.get('serial_is_unique'), 'device_class_id': e.get('device_class_id'),
                     'vendor': e.get('vendor'), 'product': e.get('product'), 'revision': e.get('revision'),
                     'friendly_name': None, 'vid': None, 'pid': None, 'drive_letters': [], 'volume_guids': [],
                     'control_sets': [], 'registry_key': None, 'source': 'SETUPAPI_LOG', 'source_detail': {}}
                for f in PROPERTY_TIMES.values():
                    d[f] = None
                devices[inst] = d
                if d.get('serial_is_unique') and d.get('serial'):
                    by_serial[d['serial'].upper()] = d
            if not d.get('setupapi_first_install') or e['install_time'] < d['setupapi_first_install']:
                d['setupapi_first_install'] = e['install_time']
                d['source_detail']['setupapi_first_install'] = 'SETUPAPI_DEV_LOG'
        elif e['bus'] == 'USB' and e.get('serial'):
            d = by_serial.get(e['serial'].upper())
            if d and not d.get('vid'):
                d['vid'], d['pid'] = e.get('vid'), e.get('pid')
    return list(devices.values())
